def get_mitre_name(code: str | None) -> str:
    if not code:
        return "Unknown"
    c = code.upper()
    return MITRE_NAMES.get(c) or MITRE_NAMES.get(c.split(".")[0], "Unknown")


def get_mitre_tactic(code: str | None) -> str:
    if not code:
        return "Unmapped"
    c = code.upper()
    return MITRE_TACTICS.get(c) or MITRE_TACTICS.get(c.split(".")[0], "Unmapped")
